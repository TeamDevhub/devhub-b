-- =====================================================
-- REPORT / NOTIFICATION / BANNER
-- =====================================================
CREATE TABLE REPORT
(
  REPORT_GUID  VARCHAR(32) PRIMARY KEY,
  BOARD_GUID   VARCHAR(255) NOT NULL,
  CATEGORY_CD  VARCHAR(255) NOT NULL,
  COMMENT_GUID VARCHAR(255) NOT NULL,
  PROCESS_YN   VARCHAR(1) NOT NULL CHECK (PROCESS_YN IN ('N','Y')),
  REASON       VARCHAR(255) NOT NULL
);

CREATE TABLE NOTIFICATION
(
  NOTIFICATION_GUID VARCHAR(32) PRIMARY KEY,
  TYPE_CD           VARCHAR(10) NOT NULL,
  IMAGE_GUID        VARCHAR(32) NOT NULL,
  RECEIVER          VARCHAR(32) NOT NULL,
  CHECKED           VARCHAR(1) NOT NULL CHECK (CHECKED IN ('N','Y')),
  CONTENT           VARCHAR(255) NOT NULL
);

CREATE TABLE BANNER
(
  BANNER_GUID            VARCHAR(32) PRIMARY KEY,
  IMAGE_GUID             VARCHAR(32) NOT NULL,
  DESCRIPTION            VARCHAR(255) NOT NULL,
  IS_MAIN_BANNER         VARCHAR(1) NOT NULL CHECK (IS_MAIN_BANNER IN ('N','Y')),
  TITLE                  VARCHAR(255) NOT NULL,
  LINK                   VARCHAR(255) NOT NULL,
  USED                   VARCHAR(1) NOT NULL CHECK (USED IN ('N','Y')),
  PUBLICATION_START_DATE TIMESTAMP(6) NOT NULL,
  PUBLICATION_END_DATE   TIMESTAMP(6) NOT NULL
);

-- =====================================================
-- TERMS / TERMS_AGREEMENT
-- =====================================================
CREATE TABLE TERMS
(
  TERMS_GUID  VARCHAR(32) PRIMARY KEY,
  CONTENT     VARCHAR(255) NOT NULL,
  DELETE_YN   VARCHAR(1) NOT NULL CHECK (DELETE_YN IN ('N','Y')),
  NAME        VARCHAR(255) NOT NULL,
  REQUIRED_YN VARCHAR(1) NOT NULL CHECK (REQUIRED_YN IN ('N','Y')),
  USE_YN      VARCHAR(1) NOT NULL CHECK (USE_YN IN ('N','Y'))
);

CREATE TABLE TERMS_AGREEMENT
(
  TERMS_AGREEMENT_GUID VARCHAR(32) PRIMARY KEY,
  TERMS_GUID           VARCHAR(255) NOT NULL,
  USER_GUID            VARCHAR(255) NOT NULL,
  AGREEMENT_YN         VARCHAR(1) NOT NULL CHECK (AGREEMENT_YN IN ('N','Y')),
  CONSTRAINT FK_TERMS_AGREE_TERMS FOREIGN KEY (TERMS_GUID)
    REFERENCES TERMS(TERMS_GUID),
  CONSTRAINT FK_TERMS_AGREE_USER FOREIGN KEY (USER_GUID)
    REFERENCES USERS(USER_GUID)
);
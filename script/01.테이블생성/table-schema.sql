-- =====================================================
-- USERS
-- =====================================================
CREATE TABLE USERS
(
  USER_GUID       VARCHAR(32) PRIMARY KEY,
  MANNER_DEGREE   DOUBLE NOT NULL,
  BLOCK_END_DATE  TIMESTAMP(6),
  LAST_LOGIN_DATE TIMESTAMP(6),
  MODIFIED_DATE   TIMESTAMP(6),
  REGISTERED_DATE TIMESTAMP(6),
  INTRODUCTION    VARCHAR(500),
  BLOCKED         VARCHAR(1) NOT NULL CHECK (BLOCKED IN ('N','Y')),
  DELETED         VARCHAR(1) NOT NULL CHECK (DELETED IN ('N','Y')),
  EMAIL           VARCHAR(255) NOT NULL UNIQUE,
  OAUTH_ID        VARCHAR(255),
  PASSWORD        VARCHAR(255) NOT NULL,
  USERNAME        VARCHAR(255),
  PROVIDER        VARCHAR(20) CHECK (PROVIDER IN ('EMAIL','GITHUB','GOOGLE','KAKAO')),
  USER_ROLE       VARCHAR(10) NOT NULL CHECK (USER_ROLE IN ('ADMIN','USER')),
  FILE_GUID       VARCHAR(255)
);

-- =====================================================
-- ATTACHMENT_FILE
-- =====================================================
CREATE TABLE ATTACHMENT_FILE
(
  FILE_GUID       VARCHAR(32) PRIMARY KEY,
  SIZE            BIGINT NOT NULL,
  MODIFIED_DATE   TIMESTAMP(6),
  REGISTERED_DATE TIMESTAMP(6),
  EXTENSION_NAME  VARCHAR(255) NOT NULL,
  ORIGINAL_NAME   VARCHAR(255) NOT NULL,
  PATH            VARCHAR(255) NOT NULL
);

-- =====================================================
-- APPLICATION_FORM
-- =====================================================
CREATE TABLE APPLICATION_FORM
(
  APPLICATION_FORM_GUID VARCHAR(32) PRIMARY KEY,
  MODIFIED_DATE         TIMESTAMP(6),
  REGISTERED_DATE       TIMESTAMP(6),
  CUSTOM_YN             VARCHAR(1) NOT NULL CHECK (CUSTOM_YN IN ('N','Y')),
  HELP_TEXT             VARCHAR(255) NOT NULL,
  TITLE                 VARCHAR(255) NOT NULL,
  TYPE_CD               VARCHAR(255) NOT NULL,
  USE_YN                VARCHAR(1) NOT NULL CHECK (USE_YN IN ('N','Y'))
);

CREATE TABLE APPLICATION_FORM_ITEM
(
  FORM_ITEM_GUID VARCHAR(32) PRIMARY KEY,
  FORM_GUID      VARCHAR(32) NOT NULL,
  CONTENT        VARCHAR(255) NOT NULL,
  CONSTRAINT FK_FORM_ITEM_FORM FOREIGN KEY (FORM_GUID)
    REFERENCES APPLICATION_FORM(APPLICATION_FORM_GUID)
);

-- =====================================================
-- PROJECT
-- =====================================================
CREATE TABLE PROJECT
(
  PROJECT_GUID           VARCHAR(32) PRIMARY KEY,
  USER_GUID              VARCHAR(32) NOT NULL,
  PROGRESS_END_DATE      DATE NOT NULL,
  PROGRESS_START_DATE    DATE NOT NULL,
  RECRUITMENT_END_DATE   DATE NOT NULL,
  RECRUITMENT_START_DATE DATE NOT NULL,
  PROGRESS_REGION_CD     VARCHAR(10),
  PROGRESS_TYPE_CD       VARCHAR(10) NOT NULL,
  RECRUITMENT_TYPE_CD    VARCHAR(10) NOT NULL,
  ATTACHMENT_FILE_GUID   VARCHAR(32),
  IMAGE_FILE_GUID        VARCHAR(32),
  CAPACITY_CLOSED_YN     VARCHAR(1) NOT NULL CHECK (CAPACITY_CLOSED_YN IN ('N','Y')),
  CATEGORY               VARCHAR(255) NOT NULL,
  CONTENT                VARCHAR(255) NOT NULL,
  DELETE_YN              VARCHAR(1) NOT NULL CHECK (DELETE_YN IN ('N','Y')),
  TITLE                  VARCHAR(255) NOT NULL,
  USERNAME               VARCHAR(255) NOT NULL,
  CONSTRAINT FK_PROJECT_USER FOREIGN KEY (USER_GUID)
    REFERENCES USERS(USER_GUID),
  CONSTRAINT FK_PROJECT_ATTACHMENT FOREIGN KEY (ATTACHMENT_FILE_GUID)
    REFERENCES ATTACHMENT_FILE(FILE_GUID)
);

CREATE TABLE PROJECT_REQUIREMENT
(
  PROJECT_REQUIREMENT_GUID VARCHAR(32) PRIMARY KEY,
  PROJECT_GUID             VARCHAR(32) NOT NULL,
  POSITION_CD              VARCHAR(10) NOT NULL,

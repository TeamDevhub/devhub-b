-- =====================================================
-- REFRESH_TOKEN / VERIFICATIONS
-- =====================================================
-- MySQL에서는 AUTO_INCREMENT 사용
CREATE TABLE REFRESH_TOKEN
(
  ID        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  TOKEN     VARCHAR(500) NOT NULL,
  USER_GUID VARCHAR(255) NOT NULL UNIQUE,
  CONSTRAINT FK_REFRESH_USER FOREIGN KEY (USER_GUID)
    REFERENCES USERS(USER_GUID)
);

CREATE TABLE VERIFICATIONS
(
  ID                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  CODE              VARCHAR(255),
  TARGET_VALUE      VARCHAR(255) NOT NULL,
  VERIFIED          VARCHAR(1) NOT NULL CHECK (VERIFIED IN ('N','Y')),
  VERIFICATION_TYPE VARCHAR(10) NOT NULL CHECK (VERIFICATION_TYPE IN ('EMAIL','OTP','SMS')),
  EXPIRED_AT        TIMESTAMP(6)
);


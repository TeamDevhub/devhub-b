  CAPACITY                 INTEGER NOT NULL,
  CONSTRAINT FK_REQUIREMENT_PROJECT FOREIGN KEY (PROJECT_GUID)
    REFERENCES PROJECT(PROJECT_GUID)
);

CREATE TABLE PROJECT_SKILL
(
  PROJECT_SKILL_GUID VARCHAR(32) PRIMARY KEY,
